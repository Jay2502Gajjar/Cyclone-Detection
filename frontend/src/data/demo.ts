import type { Cyclone } from "@/types/cyclone";

function makeSeries(wind: number, pressure: number, coast: number) {
  return Array.from({ length: 12 }).map((_, i) => ({
    t: `${String(i * 2).padStart(2, "0")}:00`,
    wind: Math.round(wind - 26 + i * 2.4 + Math.sin(i) * 5),
    pressure: Math.round(pressure + 18 - i * 1.6 + Math.cos(i) * 3),
    coastKm: Math.round(coast + 210 - i * 18),
    confidence: Math.min(96, Math.round(58 + i * 2.6)),
  }));
}

function track(lat: number, lon: number, wind: number, pressure: number) {
  return Array.from({ length: 8 }).map((_, i) => ({
    lat: +(lat - (7 - i) * 0.85).toFixed(2),
    lon: +(lon + (7 - i) * 0.72).toFixed(2),
    t: `T-${(7 - i) * 6}H`,
    windKph: Math.round(wind - (7 - i) * 11),
    pressureHpa: Math.round(pressure + (7 - i) * 6),
  }));
}

